"""NIDAR Rescue GCS — Hardware Subsystem Health Model & Diagnostics Architecture.

Defines a strict, trustworthy health status model shared across all subsystem rows,
detail diagnostics dialogs, data plugins, and bridge streams.

Status Model:
- OK: Configured data source is connected, valid, and fresh.
- WARNING: A real source reports a warning or a threshold is exceeded.
- ERROR: A component reports an error or validation check fails.
- DISCONNECTED: Expected connection is unavailable.
- STALE: Data has not arrived within its configured freshness timeout.
- SIMULATED: State is generated by an explicitly labelled simulation provider.
- NOT CONFIGURED: No source or physical driver has been configured.
"""

from __future__ import annotations

import time
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional, Tuple


class HealthState(str, Enum):
    OK = "OK"
    WARNING = "WARNING"
    ERROR = "ERROR"
    DISCONNECTED = "DISCONNECTED"
    STALE = "STALE"
    SIMULATED = "SIMULATED"
    NOT_CONFIGURED = "NOT CONFIGURED"

    @classmethod
    def from_str(cls, val: str) -> HealthState:
        v_norm = val.strip().upper().replace("_", " ")
        for member in cls:
            if member.value == v_norm:
                return member
        return cls.NOT_CONFIGURED


