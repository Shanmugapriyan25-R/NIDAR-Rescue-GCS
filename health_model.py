    def get_subsystem(self, name: str) -> Optional[SubsystemRecord]:
        if name in self.subsystems:
            return self.subsystems[name]
        alias_map = {
            "Power & Battery System": "Power & Battery",
            "IMU / GPS / Localisation": "IMU / GPS Localisation",
            "SLAM & Mapping Pipeline": "SLAM & Mapping",
            "Jetson Gimbal / Mount": "Camera & Gimbal",
            "Camera and Gimbal": "Camera & Gimbal",
        }
        mapped = alias_map.get(name)
        if mapped and mapped in self.subsystems:
            return self.subsystems[mapped]
        norm = name.lower().replace(" ", "").replace("/", "").replace("&", "")
        for k, v in self.subsystems.items():
            k_norm = k.lower().replace(" ", "").replace("/", "").replace("&", "")
            if norm == k_norm or norm in k_norm or k_norm in norm:
                return v
        return None

    def get_record(self, name: str) -> Optional[SubsystemRecord]:
        return self.get_subsystem(name)

    def inject_state(self, name: str, state: HealthState, reason: str = "") -> bool:
        return self.set_subsystem_state(name, state, reason=reason)

    def set_subsystem_state(
        self,
        name: str,
        state: HealthState,
        reason: str = "",
        error_msg: Optional[str] = None,
    ) -> bool:
        """Inject or update a subsystem's health state."""
        sub = self.subsystems.get(name)
        if not sub:
            return False
        sub.current_state = state
        if error_msg is not None:
            sub.last_error_message = error_msg
        sub.record_transition(state.value, reason or f"Set to {state.value}")
        sub.last_update_monotonic = time.monotonic()
        return True

    def update_from_telemetry_frame(self, frame: Dict[str, Any]) -> None:
        """Update subsystem metrics from incoming telemetry frame (simulated or live)."""
        is_sim = str(frame.get("source_type", "")).upper() == "SIMULATION" or self.is_simulation
        telem = frame.get("telemetry", {})
        drone = frame.get("drone", {})
        sensors = frame.get("sensors", {})
        health_dict = frame.get("health", {})

        # 1. Update Power & Battery
        bat_sub = self.subsystems.get("Power & Battery")
        if bat_sub and "battery" in telem:
            bat_pct = telem.get("battery", 87)
            volts = telem.get("voltage", 22.4)
            current = telem.get("current", 8.2)
            st = HealthState.SIMULATED if is_sim else HealthState.OK
            if isinstance(bat_pct, (int, float)):
                if bat_pct <= 10:
                    st = HealthState.ERROR
                elif bat_pct <= 20:
                    st = HealthState.WARNING
            bat_sub.update_metrics({
                "Battery Percentage": f"{bat_pct}%",
                "Voltage": f"{volts} V",
                "Current Draw": f"{current} A",
                "Remaining Capacity": f"{int(bat_pct * 50)} mAh / 5000 mAh",
            }, state=st)

        # 2. Update Flight Controller
        fc_sub = self.subsystems.get("RadioLink CrossFlight")
        if fc_sub and "mode" in telem:
            st = HealthState.SIMULATED if is_sim else HealthState.OK
            fc_sub.update_metrics({
                "Reported Flight Mode": str(telem.get("mode", "AUTONOMOUS")),
                "Telemetry Freshness": f"Link: {telem.get('link_ms', 35)} ms",
            }, state=st)

        # 3. Update RPLIDAR C1
        lidar_sub = self.subsystems.get("RPLIDAR C1")
        if lidar_sub and "lidar" in sensors:
            l_stat = str(sensors.get("lidar", "")).upper()
            st = HealthState.SIMULATED if is_sim else (HealthState.OK if l_stat == "ACTIVE" else HealthState.WARNING)
            lidar_sub.update_metrics({
                "Error State": "None · Motor Running" if l_stat == "ACTIVE" else f"Status: {l_stat}",
            }, state=st)

        # 4. Update ROS 2 Bridge
        bridge_sub = self.subsystems.get("ROS 2 Bridge")
        if bridge_sub:
            link_ms = telem.get("link_ms", 35)
            st = HealthState.SIMULATED if is_sim else HealthState.OK
            bridge_sub.update_metrics({
                "Connection Latency": f"{link_ms} ms",
            }, state=st)

        # 5. Update IMU / GPS
        imu_sub = self.subsystems.get("IMU / GPS Localisation")
        if imu_sub and "heading" in drone:
            st = HealthState.SIMULATED if is_sim else HealthState.OK
            imu_sub.update_metrics({
                "Compass Orientation": f"Yaw: {drone.get('heading', 90.0)}° · Alt: {drone.get('altitude', 2.4)}m",
                "Position Availability": "HIGH ACCURACY (Local ENU)",
            }, state=st)

        # 6. Apply any explicit health overrides from frame
        for name, val in health_dict.items():
            sub = self.subsystems.get(name)
            if sub and isinstance(val, str):
                val_upper = val.upper()
                if "SIM" in val_upper:
                    sub.current_state = HealthState.SIMULATED
                elif "WARN" in val_upper:
                    sub.current_state = HealthState.WARNING
                elif "ERR" in val_upper:
                    sub.current_state = HealthState.ERROR
                elif "DISC" in val_upper:
                    sub.current_state = HealthState.DISCONNECTED
                elif "NOT" in val_upper:
                    sub.current_state = HealthState.NOT_CONFIGURED
                elif "OK" in val_upper:
                    sub.current_state = HealthState.SIMULATED if is_sim else HealthState.OK

    def evaluate_all_freshness(self) -> None:
        """Call periodically to check if any sensor or link has gone stale."""
        for sub in self.subsystems.values():
            sub.evaluate_freshness()
