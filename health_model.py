@dataclass
class SubsystemRecord:
    """Detailed health record for a single hardware subsystem."""
    id: str
    name: str
    icon: str
    category: str
    default_state: HealthState
    source_label: str
    freshness_timeout_sec: float
    description: str
    troubleshooting: str
    metrics: Dict[str, Any] = field(default_factory=dict)
    current_state: HealthState = HealthState.NOT_CONFIGURED
    last_update_monotonic: float = field(default_factory=time.monotonic)
    last_error_message: Optional[str] = None
    status_history: List[Tuple[str, str, str]] = field(default_factory=list)  # (time_str, state, reason)

    def __post_init__(self):
        if self.current_state == HealthState.NOT_CONFIGURED:
            self.current_state = self.default_state
        self.record_transition(self.current_state.value, "Subsystem initialized")

    def record_transition(self, new_state: str, reason: str = "") -> None:
        now_str = time.strftime("%H:%M:%S")
        self.status_history.insert(0, (now_str, new_state, reason))
        if len(self.status_history) > 12:
            self.status_history.pop()

    def update_metrics(
        self,
        new_metrics: Dict[str, Any],
        state: Optional[HealthState] = None,
        source: Optional[str] = None,
        error_msg: Optional[str] = None,
        source_label: Optional[str] = None,
    ) -> None:
        self.metrics.update(new_metrics)
        self.last_update_monotonic = time.monotonic()
        src = source or source_label
        if src:
            self.source_label = src
        if error_msg is not None:
            self.last_error_message = error_msg

        if state is not None and state != self.current_state:
            old_st = self.current_state.value
            self.current_state = state
            self.record_transition(state.value, f"State transitioned from {old_st}")

    def evaluate_freshness(self) -> None:
        """Evaluate if data has gone stale (unless in NOT_CONFIGURED or DISCONNECTED)."""
        if self.current_state in {HealthState.NOT_CONFIGURED, HealthState.DISCONNECTED}:
            return
        age = time.monotonic() - self.last_update_monotonic
        if age > self.freshness_timeout_sec:
            if self.current_state != HealthState.STALE:
                self.record_transition(
                    HealthState.STALE.value,
                    f"No telemetry update for {age:.1f}s (timeout: {self.freshness_timeout_sec:.1f}s)"
                )
                self.current_state = HealthState.STALE

    def get_age_seconds(self) -> float:
        return max(0.0, time.monotonic() - self.last_update_monotonic)


